import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('src/app.js','utf8');
const elements={};
const buttons=['sight','food','shop'].map(type=>({dataset:{placeType:type},setAttribute(k,v){this[k]=v;}}));
const context=vm.createContext({document:{querySelector:s=>elements[s]??=( {} ),querySelectorAll:()=>buttons},PLACES:['sight','food','shop'].map(type=>({type,city:'札幌'})).concat({type:'sight',city:'美瑛'}),detail:{open:false},renderMarkers(){},Nearby:{radius:5000,distance:()=>10}});
vm.runInContext(source.split('const map=L.map')[0]+source.split('\n').filter(l=>l.startsWith("$('#days').onclick")||l.startsWith("$('#placeLegend').onclick")).join('\n')+'\nfunction render(){updatePlaceFilter()}',context);
const run=s=>vm.runInContext(s,context);
const choose=type=>elements['#placeLegend'].onclick({target:{closest:()=>buttons.find(b=>b.dataset.placeType===type)}});
const region=city=>elements['#days'].onclick({target:{closest:()=>({dataset:{region:city}})}});
const types=()=>run('current.map(p=>p.type).join(",")');
region('札幌');assert.equal(types(),'sight');
choose('food');assert.equal(types(),'sight,food');assert.equal(buttons[0]['aria-pressed'],'true');assert.equal(buttons[1]['aria-pressed'],'true');
choose('shop');assert.equal(types(),'sight,food,shop');
choose('sight');assert.equal(types(),'food,shop');
choose('food');choose('shop');assert.equal(types(),'');assert.match(elements['#mapHint'].textContent,/请选择/);
region('美瑛');assert.equal(types(),'sight');choose('sight');choose('food');assert.equal(types(),'');assert.match(elements['#mapHint'].textContent,/暂未添加美瑛的餐厅/);
region('札幌');choose('food');run('nearbyMode=true;userPosition={};updatePlaceFilter()');assert.equal(types(),'sight,food,sight');
console.log('Multi-select, deselection, empty states, region reset and nearby filtering passed');
